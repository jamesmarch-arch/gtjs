"""Turn the Colorfigures build script's page extras into two shared scripts.

    python tools/extract_cf_page.py

scripts/build.py inlines core.js into every figure and wraps the page with HEAD and TAIL (zoom, notices, phone layout).
The game keeps core.js as one shared file instead, so this writes HEAD and TAIL as public/figures/cf-head.js and
cf-tail.js. A figure page loads: cf-head.js, core.js, gt-bridge.js, its own script, then cf-tail.js.
Run it again after updating the skill.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUILD = ROOT / '.claude' / 'skills' / 'colorfigures' / 'scripts' / 'build.py'
OUT = ROOT / 'public' / 'figures'

ns = {'__file__': str(BUILD)}
exec(BUILD.read_text(encoding='utf-8').split('\nsrc, out = sys.argv')[0], ns)   # only the imports and the HEAD / TAIL strings


def to_js(html, name):
    parts = re.findall(r'<(style|script)>(.*?)</\1>', html, re.S)
    rest = re.sub(r'<(style|script)>.*?</\1>', '', html, flags=re.S).strip()
    if rest:
        raise SystemExit(f'{name}: unexpected markup outside <style>/<script>: {rest[:80]!r}')
    css = '\n'.join(body for tag, body in parts if tag == 'style')
    js = [f'try {{\n{body}\n}} catch (e) {{ console.error(e); }}' for tag, body in parts if tag == 'script']
    head = f'/* Generated by tools/extract_cf_page.py from the Colorfigures build script ({name}). MIT, see LICENSE. */\n'
    style = f'(() => {{ const s = document.createElement("style"); s.textContent = {json.dumps(css)}; document.head.appendChild(s); }})();\n'
    return head + style + '\n'.join(js) + '\n'


for name, key in (('cf-head.js', 'HEAD'), ('cf-tail.js', 'TAIL')):
    (OUT / name).write_text(to_js(ns[key], name), encoding='utf-8')
    print('wrote', OUT / name)
